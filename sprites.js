const SPRITE_NAMES = Object.keys(SPRITES);

// Draw a sprite on a canvas context at a given position and scale
function drawSprite(ctx, spriteName, x, y, scale) {
    const grid = SPRITES[spriteName];
    const palette = PALETTES[spriteName];
    const s = scale || SPRITE_SCALE;

    for (let row = 0; row < grid.length; row++) {
        for (let col = 0; col < grid[row].length; col++) {
            const colorIdx = grid[row][col];
            if (colorIdx === 0) continue;
            ctx.fillStyle = palette[colorIdx];
            ctx.fillRect(x + col * s, y + row * s, s, s);
        }
    }
}

// Get the pixel size of a sprite at a given scale
function spriteSize(scale) {
    return 12 * (scale || SPRITE_SCALE);
}

// Get prominent colors for a sprite type (for explosion particles)
function getSpriteColors(spriteName) {
    const palette = PALETTES[spriteName];
    return Object.values(palette);
}
